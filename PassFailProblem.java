class PassFailProblem {
    public static void main(String[] args) {

        int studentsMark = 56; // Container for student's mark
        int passMark = 40; // Container for passing mark
        
        boolean hasPassed = studentsMark >= passMark; // Boolean container for whether the student has passed
        
        System.out.println("Has the student passed? " + hasPassed); // Show the result
       
    }
}
